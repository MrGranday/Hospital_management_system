export interface PrintableInvoice {
  number: string;
  patientName: string;
  mrn: string;
  date: string;
  department: string;
  items: { description: string; qty: number; rate: number; total: number }[];
  amount: number;
  paid: number;
}

export function printInvoice(inv: PrintableInvoice) {
  const balance = inv.amount - inv.paid;
  const body = `<p style="margin-bottom:12px"><strong>Department:</strong> ${inv.department}</p><table><thead><tr><th>Description</th><th class="text-right">Qty</th><th class="text-right">Rate</th><th class="text-right">Total</th></tr></thead><tbody>${inv.items.map(i => `<tr><td>${i.description}</td><td class="text-right">${i.qty}</td><td class="text-right">$${i.rate.toFixed(2)}</td><td class="text-right">$${i.total.toFixed(2)}</td></tr>`).join("")}</tbody></table><div class="total-section"><div class="row"><span>Subtotal</span><span>$${inv.amount.toFixed(2)}</span></div><div class="row"><span>Paid</span><span>$${inv.paid.toFixed(2)}</span></div><div class="row grand"><span>Balance Due</span><span>$${balance.toFixed(2)}</span></div></div>`;
  printDoc({
    title: `Invoice ${inv.number}`,
    docType: "Invoice",
    docNum: inv.number,
    patient: inv.patientName,
    mrn: inv.mrn,
    date: new Date(inv.date).toLocaleDateString(),
    body,
  });
}

export interface PrintableReceipt {
  invoice: string;
  customer: string;
  time: string;
  paymentMethod: string;
  items: { name: string; qty: number; price: number }[];
  total: number;
}

export function printReceipt(sale: PrintableReceipt) {
  const subtotal = sale.items.reduce((s, i) => s + i.price * i.qty, 0);
  const tax = sale.total - subtotal;
  const body = `<table><thead><tr><th>Item</th><th class="text-right">Qty</th><th class="text-right">Price</th><th class="text-right">Total</th></tr></thead><tbody>${sale.items.map(i => `<tr><td>${i.name}</td><td class="text-right">${i.qty}</td><td class="text-right">$${i.price.toFixed(2)}</td><td class="text-right">$${(i.price * i.qty).toFixed(2)}</td></tr>`).join("")}</tbody></table><div class="total-section"><div class="row"><span>Subtotal</span><span>$${subtotal.toFixed(2)}</span></div><div class="row"><span>Tax (8%)</span><span>$${tax.toFixed(2)}</span></div><div class="row grand"><span>Total</span><span>$${sale.total.toFixed(2)}</span></div></div>`;
  printDoc({ title: `Receipt ${sale.invoice}`, docType: "Receipt", docNum: sale.invoice, patient: sale.customer, mrn: "N/A", date: sale.time, body });
}

export interface PrintablePrescription {
  number: string;
  patientName: string;
  mrn: string;
  date: string;
  doctorName: string;
  items: { name: string; qty: number; dosage: string }[];
}

export function printPrescription(rx: PrintablePrescription) {
  const body = `<div class="rx-symbol">℞</div><p style="margin-bottom:12px"><strong>Prescribed by:</strong> ${rx.doctorName}</p><table><thead><tr><th>#</th><th>Medication</th><th>Dosage</th><th class="text-right">Qty</th></tr></thead><tbody>${rx.items.map((item, i) => `<tr><td>${i + 1}</td><td><strong>${item.name}</strong></td><td>${item.dosage}</td><td class="text-right">${item.qty}</td></tr>`).join("")}</tbody></table>`;
  printDoc({ title: `Prescription ${rx.number}`, docType: "Prescription", docNum: rx.number, patient: rx.patientName, mrn: rx.mrn, date: new Date(rx.date).toLocaleDateString(), body, footer: "This prescription is valid for 30 days." });
}

export interface PrintableLabReport {
  number: string;
  patientName: string;
  mrn: string;
  date: string;
  orderedBy: string;
  tests: { name: string; result: string; range: string; flag?: "normal" | "high" | "low" }[];
}

export function printLabReport(r: PrintableLabReport) {
  const body = `<p style="margin-bottom:12px"><strong>Ordered by:</strong> ${r.orderedBy}</p><table><thead><tr><th>Test</th><th>Result</th><th>Reference Range</th><th>Flag</th></tr></thead><tbody>${r.tests.map(t => `<tr><td><strong>${t.name}</strong></td><td>${t.result}</td><td>${t.range}</td><td>${t.flag && t.flag !== "normal" ? `<span style="color:${t.flag === "high" ? "#dc2626" : "#2563eb"};font-weight:600">${t.flag.toUpperCase()}</span>` : "Normal"}</td></tr>`).join("")}</tbody></table>`;
  printDoc({ title: `Lab Report ${r.number}`, docType: "Lab Report", docNum: r.number, patient: r.patientName, mrn: r.mrn, date: new Date(r.date).toLocaleDateString(), body, footer: "Results are confidential and intended for clinical use only." });
}

// CSV export helper
export function exportToCsv(filename: string, rows: Record<string, any>[]) {
  if (!rows.length) return;
  const headers = Object.keys(rows[0]);
  const escape = (v: any) => {
    const s = v === null || v === undefined ? "" : String(v);
    return `"${s.replace(/"/g, '""')}"`;
  };
  const csv = [
    headers.join(","),
    ...rows.map(r => headers.map(h => escape(r[h])).join(",")),
  ].join("\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
